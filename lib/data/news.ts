function wordCount(blocks: Block[]) {
  const text = blocks
    .map((b) => {
      switch (b.type) {
        case "p":
        case "h":
          return b.text;
        case "list":
          return b.items.join(" ");
        case "callout":
          return `${b.title} ${b.text}`;
        case "quote":
          return b.text;
        case "table":
          return [...b.head, ...b.rows.flat()].join(" ");
      }
    })
    .join(" ");
  return text.split(/\s+/).filter(Boolean).length;
}

