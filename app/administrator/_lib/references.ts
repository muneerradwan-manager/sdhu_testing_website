/** The references as the administration left them */
export function useAdminRefs() {
  const refs = useStore((s) => s.adminRefs);
  const s = useStructure();
  return useMemo(() => {
    const roles: (Pick<RoleDef, "key" | "name" | "desc"> & { level: string; secondary?: boolean })[] = [
      ...s.roles.map((r) => ({ key: r.key, name: r.name, desc: r.desc, level: r.level === "cluster" ? "تكتل" : r.level === "group" ? "مجموعة" : "مشترك" })),
      ...Object.entries(SECONDARY).map(([key, name]) => ({ key, name, desc: "", level: "تكتل", secondary: true })),
    ];
    const all: JobDescription[] = roles.map((r) => {
      const edit = refs.jobs?.[r.key];
      const base = JOBS[r.key];
      return { key: r.key, name: r.name, level: r.level, secondary: r.secondary, summary: edit?.summary ?? base?.summary ?? r.desc, duties: edit?.duties ?? base?.duties ?? [], hidden: !!edit?.hidden };
    });
    const order = refs.jobOrder ?? [];
    const jobs = [...all].sort((a, b) => (order.includes(a.key) ? order.indexOf(a.key) : 999) - (order.includes(b.key) ? order.indexOf(b.key) : 999));
    return { jobs, system: refs.system ?? DEFAULT_SYSTEM, decisions: refs.decisions ?? DEFAULT_DECISIONS, contracts: refs.contracts ?? DEFAULT_CONTRACTS, edited: refs };
  }, [refs, s]);
}

/** A section's text as paragraphs and lists: blank lines part paragraphs, «- » starts an item, «**…**» is bold */
export type Block = { kind: "p"; text: string } | { kind: "ul"; items: string[] };
export function blocksOf(body: string): Block[] {
  const out: Block[] = [];
  for (const chunk of body.split(/\n\s*\n/)) {
    const lines = chunk.split("\n").filter((l) => l.trim());
    if (!lines.length) continue;
    if (lines.every((l) => l.trim().startsWith("- "))) out.push({ kind: "ul", items: lines.map((l) => l.trim().slice(2)) });
    else out.push({ kind: "p", text: lines.join(" ") });
  }
  return out;
}

/** «**المجموعة**: …» into its bold and plain parts */
export function boldParts(text: string) {
  return text.split(/(\*\*[^*]+\*\*)/).map((t) => (t.startsWith("**") && t.endsWith("**") ? { bold: true, text: t.slice(2, -2) } : { bold: false, text: t }));
}
